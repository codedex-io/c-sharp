using System;

class NotificationOverload
{
  static void Main()
  {
    string[] messages =
    {
      "where are you???",
      "check the group chat",
      "we're ordering food",
      "bring snacks",
      "see you soon!"
    };

    for (int i = 0; i < messages.Length; i++)
    {
      Console.WriteLine(messages[i]);
    }
  }
}