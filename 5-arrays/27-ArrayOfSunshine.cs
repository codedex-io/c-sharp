using System;

class ArrayOfSunshine
{
  static void Main()
  {
    string[] movies =
    {
      "Jaws",
      "Jurassic Park",
      "The Parent Trap",
      "Barbie"
    };

    int[] ratings = { 97, 91, 87, 88 };

    Console.WriteLine(movies[0] + " - " + ratings[0]);
    Console.WriteLine(movies[1] + " - " + ratings[1]);
    Console.WriteLine(movies[2] + " - " + ratings[2]);
    Console.WriteLine(movies[3] + " - " + ratings[3]);
  }
}